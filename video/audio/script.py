"""Voice-over script: the single source for narration.md and captions.srt.

Run `python3 -m video.audio.script` to regenerate both files after editing LINES.
Each scene gets a speech window [start + LEAD, end - TAIL]; captions inside it
are timed proportionally to word count. Pace must stay <= MAX_WPS words/second.

Numbers in the "results" scene must match video/metrics.json (QA checks this).
"""
from __future__ import annotations

import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
STORYBOARD = ROOT / "video" / "storyboard.json"
HERE = Path(__file__).resolve().parent
MAX_WPS = 2.3
LEAD, TAIL, GAP = 0.4, 0.35, 0.12

# scene id -> list of caption lines (each line is one subtitle cue)
LINES: dict[str, list[str]] = {
    "hook": [
        "One patient. Eight letters.",
        "An anaesthetist, a surgeon and an emergency doctor each need different facts.",
    ],
    "problem": [
        "Letters copy each other, so errors travel.",
        "One duplex report says the right carotid; every other letter says left.",
        "A twelve kilo weight loss is mentioned nowhere.",
    ],
    "ask": [
        "Second Eye starts from one sentence.",
        "The anaesthetist types her task, and the app works out the role and what that task needs.",
    ],
    "screen": [
        "One screen, only what matters: blood thinner, allergy, heart function,",
        "and what is not documented.",
        "Click any fact and the original German sentence lights up, with an English translation.",
    ],
    "switch": [
        "Switch the doctor, keep the patient.",
        "The surgeon and the emergency physician each get a different screen, built for their task.",
    ],
    "disagree": [
        "The record disagrees with itself.",
        "Second Eye found five contradictions and shows both passages side by side.",
        "It also lists blind spots and follow-ups that were never closed.",
    ],
    "how": [
        "How it works: AI points, code verifies.",
        "Every quote is checked against the letters, so nothing is made up.",
        "Rules handle what rules can.",
        "Built on IBM's MLA output and the IPS structure.",
    ],
    "results": [
        "On the five test situations: fifteen of fifteen answers, every fact linked, zero invented.",
        "Not yet: the PIN lock isn't wired in, and guideline citations still need a second reviewer.",
    ],
    "close": [
        "Other tools summarise the record.",
        "Second Eye checks it, for the task in front of you.",
    ],
}


def words(s: str) -> int:
    return len(re.findall(r"[A-Za-z0-9'’-]+", s))


def load_scenes() -> list[dict]:
    return json.loads(STORYBOARD.read_text())["scenes"]


def timed_cues() -> list[dict]:
    """[{scene, start, end, text}] with times in seconds."""
    cues = []
    for sc in load_scenes():
        lines = LINES.get(sc["id"], [])
        if not lines:
            continue
        w0, w1 = sc["start"] + LEAD, sc["end"] - TAIL
        total_w = sum(words(l) for l in lines)
        span = (w1 - w0) - GAP * (len(lines) - 1)
        t = w0
        for line in lines:
            d = span * words(line) / total_w
            cues.append({"scene": sc["id"], "start": round(t, 3), "end": round(t + d, 3), "text": line})
            t += d + GAP
    return cues


def srt_time(t: float) -> str:
    ms = int(round(t * 1000))
    h, ms = divmod(ms, 3600000)
    m, ms = divmod(ms, 60000)
    s, ms = divmod(ms, 1000)
    return f"{h:02d}:{m:02d}:{s:02d},{ms:03d}"


def wrap(text: str, width: int = 44) -> str:
    if len(text) <= width:
        return text
    words_ = text.split()
    best, best_diff = text, 10 ** 9
    for i in range(1, len(words_)):
        a, b = " ".join(words_[:i]), " ".join(words_[i:])
        diff = max(len(a), len(b))
        if diff < best_diff:
            best, best_diff = a + "\n" + b, diff
    return best


def write_srt(path: Path) -> None:
    out = []
    for i, c in enumerate(timed_cues(), 1):
        out.append(f"{i}\n{srt_time(c['start'])} --> {srt_time(c['end'])}\n{wrap(c['text'])}\n")
    path.write_text("\n".join(out))


def write_md(path: Path) -> None:
    scenes = load_scenes()
    md = ["# Narration: Second Eye (submission video)", "",
          "Generated by `python3 -m video.audio.script` from `video/audio/script.py`; edit there, not here.",
          f"Timings follow `video/storyboard.json`. Pace limit: {MAX_WPS} words/s per scene "
          f"(speech window = scene start + {LEAD} s to scene end - {TAIL} s).",
          "The challenge requires the video to say what works and what does not: see *results*.",
          "Numbers spoken in *results* and *disagree* must match `video/metrics.json` (checked by `python3 -m video.qa.check`).",
          "", "| Scene | Time | Words | Pace (w/s) |", "|---|---|---|---|"]
    rows, body = [], []
    for sc in scenes:
        lines = LINES.get(sc["id"], [])
        w = sum(words(l) for l in lines)
        win = (sc["end"] - TAIL) - (sc["start"] + LEAD)
        rows.append(f"| {sc['id']} | {sc['start']}-{sc['end']} s | {w} | {w / win:.2f} |")
        body += [f"## {sc['id']} ({sc['start']}-{sc['end']} s)", "",
                 f"*Picture:* {sc['beat']}  ", f"*Music/SFX:* {sc['audio']}", ""]
        for c in [c for c in timed_cues() if c["scene"] == sc["id"]]:
            body.append(f"- `{c['start']:6.2f}-{c['end']:6.2f}` {c['text']}")
        body.append("")
    path.write_text("\n".join(md + rows + [""] + body))


def check_pace() -> list[str]:
    problems = []
    for sc in load_scenes():
        w = sum(words(l) for l in LINES.get(sc["id"], []))
        win = (sc["end"] - TAIL) - (sc["start"] + LEAD)
        if w / win > MAX_WPS:
            problems.append(f"{sc['id']}: {w} words in {win:.1f} s = {w / win:.2f} w/s > {MAX_WPS}")
    return problems


if __name__ == "__main__":
    for p in check_pace():
        print("PACE:", p)
    write_srt(HERE / "captions.srt")
    write_md(HERE / "narration.md")
    print("wrote", HERE / "captions.srt", "and", HERE / "narration.md")
