import React from "react";
import { AbsoluteFill, useCurrentFrame } from "remotion";
import { M } from "../data";
import { C, FONT, MONO } from "../theme";
import { spr, tween } from "../lib";
import { Kicker, Words, Count } from "../components/Text";
import { Glass, Mark } from "../components/Bits";

const TW = 318;
const TG = 26;

export const Results: React.FC<{ dur: number }> = () => {
  const f = useCurrentFrame();
  const PB = 228;
  const exitA = tween(f, PB - 16, 16);
  const q: any[] = M.questions;
  const tiles = [
    { n: M.correct, of: M.total, label: "answers correct and linked", sub: `${M.situations.length} situations, scored on the screen` },
    { n: M.traceability.pct, suffix: "%", label: "facts linked to their sentence", sub: `${M.traceability.linked} of ${M.traceability.facts_on_screen} on screen` },
    { n: M.facts.unverified_on_screen, label: "invented facts", sub: `every fact on screen matched word for word; ${M.facts.dropped_at_load} of ${M.facts.total} dropped at load` },
    { n: M.contradictions.counted, label: "contradictions found", sub: `+${M.contradictions.notes} documentation notes, apart` },
    { n: Math.round(M.latency.slowest_ms), suffix: " ms", label: "slowest screen", sub: `median ${Math.round(M.latency.median_ms)} ms · ${M.latency.requests} ${M.latency.source} requests` },
  ];
  const left0 = (1920 - (tiles.length * TW + (tiles.length - 1) * TG)) / 2;
  return (
    <AbsoluteFill>
      <div style={{ opacity: 1 - exitA, transform: `translateY(${-exitA * 30}px)` }}>
        <div style={{ position: "absolute", left: left0, top: 130 }}>
          <Kicker text="Results · the 5 case situations" at={0} />
          <div style={{ height: 24 }} />
          <Words text="Measured, not claimed." at={6} size={76} />
        </div>
        {tiles.map((t, i) => {
          const s = spr(f, 30 + i * 12, 120, 17);
          const at = 36 + i * 12;
          return (
            <div key={i} style={{ position: "absolute", left: left0 + i * (TW + TG), top: 380, width: TW, height: 400, opacity: Math.min(1, s * 1.4), transform: `translateY(${(1 - s) * 50}px)` }}>
              <Glass style={{ height: "100%", boxSizing: "border-box", padding: "34px 30px" }}>
                <div style={{ fontSize: 96, fontWeight: 800, letterSpacing: "-0.05em", color: i === 0 ? C.tealHi : C.ink, lineHeight: 1, whiteSpace: "nowrap" }}>
                  <Count to={t.n} at={at} dur={44} decimals={Number.isInteger(t.n) ? 0 : 1} />
                  {t.of !== undefined && <span style={{ color: C.muted }}>/{t.of}</span>}
                  {t.suffix && <span style={{ fontSize: t.suffix.trim() === "ms" ? 44 : 72 }}>{t.suffix}</span>}
                </div>
                {i === 0 && (
                  <div style={{ display: "flex", gap: 6, marginTop: 22 }}>
                    {q.map((x, j) => (
                      <div key={x.id} style={{ flex: 1, height: 10, borderRadius: 5, background: f >= at + j * 2.6 ? (x.pass ? C.tealHi : C.alert) : C.line2 }} />
                    ))}
                  </div>
                )}
                <div style={{ fontSize: 27, fontWeight: 600, marginTop: i === 0 ? 24 : 56, lineHeight: 1.2 }}>{t.label}</div>
                <div style={{ fontSize: 19, color: C.muted, marginTop: 12, lineHeight: 1.35 }}>{t.sub}</div>
              </Glass>
            </div>
          );
        })}
        <div style={{ position: "absolute", left: left0, top: 830, fontFamily: MONO, fontSize: 18, color: C.muted, opacity: tween(f, 110, 20) }}>
          numbers generated by video/scripts/export_metrics.py from the running system
        </div>
      </div>

      {f >= PB - 2 && (
        <>
          <div style={{ position: "absolute", left: 140, top: 130, width: 1000 }}>
            <Kicker text="Honest status" at={PB} color={C.amber} />
            <div style={{ height: 24 }} />
            <Words text="What does not work yet." at={PB + 6} size={76} />
          </div>
          <div style={{ position: "absolute", left: 140, top: 360, width: 1640, display: "grid", gridTemplateColumns: "1fr 1fr", columnGap: 60, rowGap: 26 }}>
            {(M.not_yet as string[]).map((t, i) => {
              const s = spr(f, PB + 26 + i * 9, 130, 17);
              return (
                <div key={t} style={{ display: "flex", gap: 18, alignItems: "flex-start", fontFamily: FONT, fontSize: 30, lineHeight: 1.3, color: C.ink, opacity: Math.min(1, s * 1.4), transform: `translateY(${(1 - s) * 24}px)`, padding: "22px 26px", borderRadius: 16, background: "rgba(245,241,234,0.04)", border: `1px solid ${C.line}` }}>
                  <div style={{ marginTop: 4 }}>
                    <Mark status="not_documented" size={30} />
                  </div>
                  {t}
                </div>
              );
            })}
          </div>
        </>
      )}
    </AbsoluteFill>
  );
};
